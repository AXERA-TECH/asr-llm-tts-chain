struct AsrStats {
  std::size_t characters = 0, punctuation = 0;
  double Ratio() const {
    return characters ? static_cast<double>(punctuation) / characters : 1.0;
  }
  bool Accept(int minimum, double maximum_ratio) const {
    return characters > static_cast<std::size_t>(minimum) && Ratio() < maximum_ratio;
  }
};

inline AsrStats AnalyzeAsr(const std::string& text) {
  AsrStats stats;
  for (std::size_t i = 0; i < text.size();) {
    const auto cp = Next(text, &i);
    if (IsSpace(cp)) continue;
    ++stats.characters;
    if (IsPunctuation(cp)) ++stats.punctuation;
  }
  return stats;
}
