// Decode one complete UTF-8 code point. Invalid input counts as a symbol.
inline uint32_t Next(const std::string& text, std::size_t* offset) {
  const auto lead = static_cast<unsigned char>(text[(*offset)++]);
  if (lead < 0x80) return lead;
  const int count = lead >= 0xC2 && lead <= 0xDF ? 1 :
                    lead >= 0xE0 && lead <= 0xEF ? 2 :
                    lead >= 0xF0 && lead <= 0xF4 ? 3 : -1;
  if (count < 0 || *offset + count > text.size()) return 0xFFFD;
  uint32_t cp = lead & ((1u << (6 - count)) - 1);
  for (int i = 0; i < count; ++i) {
    const auto byte = static_cast<unsigned char>(text[*offset]);
    if ((byte & 0xC0) != 0x80) return 0xFFFD;
    ++*offset;
    cp = (cp << 6) | (byte & 0x3F);
  }
  if ((count == 1 && cp < 0x80) || (count == 2 && cp < 0x800) ||
      (count == 3 && cp < 0x10000) || cp > 0x10FFFF ||
      (cp >= 0xD800 && cp <= 0xDFFF)) return 0xFFFD;
  return cp;
}

inline bool IsSpace(uint32_t cp) {
  return cp <= 0x20 || cp == 0x7F || cp == 0x85 || cp == 0xA0 ||
      cp == 0x1680 || (cp >= 0x2000 && cp <= 0x200F) ||
      cp == 0x2028 || cp == 0x2029 || cp == 0x202F || cp == 0x205F ||
      (cp >= 0x2060 && cp <= 0x206F) || cp == 0x3000 || cp == 0xFEFF;
}

inline bool IsChinese(uint32_t cp) {
  return (cp >= 0x3400 && cp <= 0x4DBF) ||
      (cp >= 0x4E00 && cp <= 0x9FFF) || (cp >= 0xF900 && cp <= 0xFAFF) ||
      (cp >= 0x20000 && cp <= 0x323AF);
}

